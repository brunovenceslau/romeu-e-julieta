package cli

import (
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"strconv"
	"strings"
)

// Page is one file a generator of this package writes: its
// slash-separated path from the root of the tree and its bytes.
type Page struct {
	Path    string
	Content []byte
}

// The files ErrorPages writes from the error table (12 12.3): the
// reference of the error ids, that of the exit codes, and the exit-code
// section of every --help.
const (
	ErrorsPath    = "docs/reference/errors.md"
	ExitCodesPath = "docs/reference/exit-codes.md"
	ExitCodesGo   = "internal/cli/exitcodes_gen.go"
)

// ErrorPages reads the error table that the errors.go files below
// internal/ of the tree fsys declare (ReadTable) and returns the three
// consumers of 12 12.3, or none for a tree with no internal/, such as a
// fixture of the generated check of tools/ci.
func ErrorPages(fsys fs.FS) ([]Page, error) {
	rows, err := ReadTable(fsys)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	gosrc, err := exitCodesGoFile()
	if err != nil {
		return nil, err
	}
	return []Page{
		{Path: ErrorsPath, Content: ErrorsPage(rows)},
		{Path: ExitCodesPath, Content: ExitCodesPage(rows)},
		{Path: ExitCodesGo, Content: gosrc},
	}, nil
}

// cell returns s for a cell of a Markdown table, with each "|" escaped.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// recovered returns the "recovered in" cell: a link to the docs/guide/
// anchor, or the "none: <reason>" text as it is.
func recovered(s string) string {
	if strings.HasPrefix(s, "docs/guide/") {
		return fmt.Sprintf("[%s](../../%s)", strings.TrimPrefix(s, "docs/"), s)
	}
	return cell(s)
}

// ErrorsPage returns docs/reference/errors.md: one line per declared id,
// sorted by id, with its slug, exit code, fix hint (a code span: a hint
// holds no backtick), the package that declares it and the link to its
// recovery (04 4.1, Error ids).
func ErrorsPage(rows []Declared) []byte {
	var b strings.Builder
	b.WriteString(`---
type: reference
reader: a user who met an error of romeu or julieta, or a contributor who adds one
---

<!-- Generated by "go generate ./..." from the error table of internal/cli, the errors.go file of each package. Do not edit by hand. -->

# Errors

Every error has a stable id, a slug, an exit code and a fix hint,
declared in the errors.go of the package that raises it
([04 4.1](../spec/04-cli.md#error-ids)). An id is never reused; the
exit codes are in [exit-codes.md](exit-codes.md).

| Id | Slug | Exit | Fix | Declared in | Recovered in |
|---|---|---|---|---|---|
`)
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | `%s` | %d | `%s` | [%s](../../%s) | %s |\n",
			r.ID, r.Slug, r.Exit, cell(r.Fix), strings.TrimSuffix(r.File, "/errors.go"), r.File, recovered(r.RecoveredIn))
	}
	return []byte(b.String())
}

// ExitCodesPage returns docs/reference/exit-codes.md: each exit status
// of both binaries with its meaning and the ids that exit with it, then
// the precedence sentence of 04 4.1, Signals.
func ExitCodesPage(rows []Declared) []byte {
	var b strings.Builder
	b.WriteString(`---
type: reference
reader: a user or a script that reads the exit status of romeu or julieta
---

<!-- Generated by "go generate ./..." from the exit codes and the error table of internal/cli. Do not edit by hand. -->

# Exit codes

Both binaries exit with one of these statuses
([04 4.1](../spec/04-cli.md#41-conventions-both-binaries)); each error
of [errors.md](errors.md) names its own.

| Exit | Meaning | Ids |
|---|---|---|
`)
	for _, e := range ExitCodes {
		var ids []string
		for _, r := range rows {
			if r.Exit == e.Code {
				ids = append(ids, "`"+r.ID+"`")
			}
		}
		fmt.Fprintf(&b, "| %d | %s | %s |\n", e.Code, cell(e.Meaning), strings.Join(ids, ", "))
	}
	fmt.Fprintf(&b, "\n%s\n", SignalPrecedence)
	return []byte(b.String())
}

// ExitCodesSection returns the exit-code section of every --help, from
// ExitCodes (04 4.1, Exit codes; Signals).
func ExitCodesSection() string {
	var b strings.Builder
	b.WriteString("Exit codes:\n")
	for _, e := range ExitCodes {
		fmt.Fprintf(&b, "  %-4d %s\n", e.Code, e.Meaning)
	}
	b.WriteString(SignalPrecedence + "\n")
	return b.String()
}

// exitCodesGoFile returns internal/cli/exitcodes_gen.go, which holds
// ExitCodesSection as the constant the help prints. It carries no
// generated-code header, so every lint finding in it stays visible (ADR
// 0015, decision 7).
func exitCodesGoFile() ([]byte, error) {
	var b strings.Builder
	b.WriteString(`// SPDX-FileCopyrightText: 2026 Bruno Venceslau
// SPDX-License-Identifier: GPL-3.0-only

package cli

// exitCodesHelp is the exit-code section of every --help. "go generate
// ./..." writes this file from ExitCodes (generate_errors.go); do not
// edit it by hand.
const exitCodesHelp = `)
	var quoted []string
	for line := range strings.SplitAfterSeq(ExitCodesSection(), "\n") {
		if line != "" {
			quoted = append(quoted, strconv.Quote(line))
		}
	}
	b.WriteString(strings.Join(quoted, " +\n\t") + "\n")
	return format.Source([]byte(b.String()))
}
