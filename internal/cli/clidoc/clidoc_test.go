// The fixture definitions whose pages the tests read: romeu docfixture,
// which runs the preflight, takes the lock and appends, and julieta
// docgroup one, a subcommand.
var (
	_ = cli.Register(func() cli.Command {
		c := cli.Define(cli.PreflightRuns, cli.LockTaken, cli.Appends("a salvage record"), cli.SnapshotNone, cli.AppendsEachRun)
		c.Binary, c.Name, c.JSON = "romeu", "docfixture", true
		c.New = func(*cli.Env) *cobra.Command {
			cmd := &cobra.Command{
				Use:     "docfixture <name>",
				Short:   "a command of the tests",
				Example: "romeu docfixture box",
				Args:    cobra.ExactArgs(1),
				RunE:    func(*cobra.Command, []string) error { return nil },
			}
			cmd.Flags().String("from", "origin", "the `ref` to start from")
			return cmd
		}
		return c
	}())
	_ = cli.Register(func() cli.Command {
		c := cli.Define(cli.PreflightNone, cli.LockNone, cli.AppendsNothing(), cli.SnapshotNone, cli.ReadsOnly)
		c.Binary, c.Name, c.Sub = "julieta", "docgroup", "one"
		c.New = func(*cli.Env) *cobra.Command {
			return &cobra.Command{Use: "one", Short: "the first", Args: cobra.NoArgs, RunE: func(*cobra.Command, []string) error { return nil }}
		}
		return c
	}())
)

// pages returns the pages CommandPages writes for the module, by path.
func pages(t *testing.T) map[string]string {
	t.Helper()
	root, err := os.OpenRoot("../../..")
	require.NoError(t, err)
	defer func() { _ = root.Close() }()
	got, err := clidoc.CommandPages(root)
	require.NoError(t, err)
	byPath := map[string]string{}
	for _, p := range got {
		_, dup := byPath[p.Path]
		require.False(t, dup, "one page per path: %s", p.Path)
		byPath[p.Path] = string(p.Content)
	}
	return byPath
}

// TestCommandPages writes one page per command of each tree, the words
// of its path as directories: the roots, the group, the definitions and
// the completion commands, and no page of help or of a hidden command.
func TestCommandPages(t *testing.T) {
	got := pages(t)
	for _, p := range []string{
		"docs/reference/romeu.md",
		"docs/reference/romeu/docfixture.md",
		"docs/reference/romeu/completion.md",
		"docs/reference/romeu/completion/bash.md",
		"docs/reference/julieta.md",
		"docs/reference/julieta/docgroup.md",
		"docs/reference/julieta/docgroup/one.md",
	} {
		assert.Contains(t, got, p)
	}
	for p := range got {
		assert.NotContains(t, p, "help", p)
		assert.NotContains(t, p, "__complete", p)
	}
}

// TestCommandPageOfADefinition shows the page of the fixture definition:
// the front matter and the generated-file header (REQ-1117), cobra/doc's
// synopsis, flags and example with no date tag, links that resolve from
// the page's directory, the side-effect fields with the P marker and the
// appending list, then the exit codes (REQ-1109).
func TestCommandPageOfADefinition(t *testing.T) {
	page := pages(t)["docs/reference/romeu/docfixture.md"]
	require.NotEmpty(t, page)
	assert.True(t, strings.HasPrefix(page, "---\ntype: reference\nreader: "), page)
	assert.Contains(t, page, "\n---\n\n<!--\nCode generated by tools/ci generate. DO NOT EDIT.\nSource: internal/cli and internal/cmd/romeu/** (the command tree of romeu, written through internal/cli/clidoc)\n\nGenerated by this command:\n\n\tgo generate ./...\n\n-->\n\n# romeu docfixture\n\na command of the tests\n")
	assert.Contains(t, page, "```\nromeu docfixture <name> [flags]\n```\n")
	assert.Contains(t, page, "      --from ref   the ref to start from (default \"origin\")\n")
	assert.Contains(t, page, "      --json       print one JSON document\n")
	assert.Contains(t, page, "### Examples\n\n```\nromeu docfixture box\n```\n")
	assert.Contains(t, page, "* [romeu](../romeu.md) - the commands that run on the host\n")
	assert.NotContains(t, page, "Auto generated")
	assert.NotContains(t, page, "\t - ", "cobra's tab before a summary is a space")
	assert.Contains(t, page, "### Side effects\n\n- **P** (preflight): yes, the command runs the preflight before its sbx calls\n- Lock: yes, the romeu lock, for the whole command\n- Appends on each run: a salvage record\n")
	assert.Contains(t, page, "| 143 | ended by SIGTERM |\n")
	assert.True(t, strings.HasSuffix(page, "\n"+cli.SignalPrecedence+"\n"), page)
}

// TestCommandPageOfAGroup shows the page of a group command: its
// synopsis names the command it needs, it links its subcommands, and it
// lists no side-effect fields, since it has no definition.
func TestCommandPageOfAGroup(t *testing.T) {
	got := pages(t)
	group := got["docs/reference/julieta/docgroup.md"]
	assert.Contains(t, group, "```\njulieta docgroup <command> [flags]\n```\n")
	assert.Contains(t, group, "* [julieta docgroup one](docgroup/one.md) - the first\n")
	assert.NotContains(t, group, "### Side effects")
	assert.Contains(t, got["docs/reference/julieta/docgroup/one.md"], "* [julieta docgroup](../docgroup.md) - the docgroup commands\n")
	assert.Contains(t, got["docs/reference/julieta.md"], "* [julieta docgroup](julieta/docgroup.md) - the docgroup commands\n")
}

// TestCommandPagesOfAFixtureTree writes no page for a tree with no
// internal/cli, as the fixtures of the generated check of tools/ci are.
func TestCommandPagesOfAFixtureTree(t *testing.T) {
	root, err := os.OpenRoot(t.TempDir())
	require.NoError(t, err)
	defer func() { _ = root.Close() }()
	got, err := clidoc.CommandPages(root)
	require.NoError(t, err)
	assert.Empty(t, got)
}

// TestErrorPages hands tools/ci the pages of the error table of the
// module.
func TestErrorPages(t *testing.T) {
	root, err := os.OpenRoot("../../..")
	require.NoError(t, err)
	defer func() { _ = root.Close() }()
	got, err := clidoc.ErrorPages(root)
	require.NoError(t, err)
	require.Len(t, got, 3)
	assert.Equal(t, cli.ErrorsPath, got[0].Path)
}
