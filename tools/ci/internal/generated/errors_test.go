package generated

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/brunovenceslau/romeu-e-julieta/internal/cli"
)

// rows are two declared rows: one recovered in a guide, one with none.
var rows = []cli.Declared{
	{Row: cli.Row{ID: "RJ-301", Slug: "approval", Exit: 3, Fix: "romeu approve <name>", RecoveredIn: "docs/guide/approve.md#gate-2"}, File: "internal/gate/errors.go"},
	{Row: cli.Row{ID: "RJ-348", Slug: "internal", Exit: 1, Fix: "decide: a | b", RecoveredIn: "none: a defect"}, File: "internal/cli/errors.go"},
}

// TestErrorsPage writes the front matter, the header and one line per
// id, with the link of its recovery and of the package that declares it.
func TestErrorsPage(t *testing.T) {
	page := string(ErrorsPage(rows))
	assert.True(t, strings.HasPrefix(page, "---\ntype: reference\nreader: "), page)
	assert.Contains(t, page, "<!-- Generated by \"go generate ./...\"")
	assert.Contains(t, page, "| `RJ-301` | `approval` | 3 | `romeu approve <name>` | [internal/gate](../../internal/gate/errors.go) | [guide/approve.md#gate-2](../../docs/guide/approve.md#gate-2) |\n")
	assert.Contains(t, page, "| `RJ-348` | `internal` | 1 | `decide: a \\| b` | [internal/cli](../../internal/cli/errors.go) | none: a defect |\n")
}

// TestExitCodesPage lists every exit status with its ids, 130 and 143
// among them, then the precedence sentence of 04 4.1, Signals.
func TestExitCodesPage(t *testing.T) {
	page := string(ExitCodesPage(rows))
	assert.True(t, strings.HasPrefix(page, "---\ntype: reference\nreader: "), page)
	assert.Contains(t, page, "| 1 | the operation failed | `RJ-348` |\n")
	assert.Contains(t, page, "| 3 | approval required | `RJ-301` |\n")
	assert.Contains(t, page, "| 130 | ended by SIGINT |  |\n")
	assert.Contains(t, page, "| 143 | ended by SIGTERM |  |\n")
	assert.True(t, strings.HasSuffix(page, "\n"+cli.SignalPrecedence+"\n"), page)
}
