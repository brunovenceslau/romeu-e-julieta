package generated

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"strings"

	"github.com/brunovenceslau/romeu-e-julieta/internal/cli"
	"github.com/brunovenceslau/romeu-e-julieta/tools/ci/internal/check"
)

// The pages generate writes from the error table of internal/cli (12
// 12.3): the reference of the error ids and that of the exit codes.
const (
	ErrorsPath    = "docs/reference/errors.md"
	ExitCodesPath = "docs/reference/exit-codes.md"
)

// errorPages reads the error table that the errors.go files below
// internal/ declare (cli.ReadTable) and returns the two pages, or none
// for a tree with no internal/.
func errorPages(root *os.Root) ([]check.Output, error) {
	rows, err := cli.ReadTable(root.FS())
	if errors.Is(err, fs.ErrNotExist) {
		// A tree with no internal/, as the fixtures of the generated
		// check are, has no error table and so no pages of it.
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return []check.Output{
		{Path: ErrorsPath, Content: ErrorsPage(rows)},
		{Path: ExitCodesPath, Content: ExitCodesPage(rows)},
	}, nil
}

// recovered returns the "recovered in" cell: a link to the docs/guide/
// anchor, or the "none: <reason>" text as it is.
func recovered(s string) string {
	if strings.HasPrefix(s, "docs/guide/") {
		return fmt.Sprintf("[%s](../../%s)", strings.TrimPrefix(s, "docs/"), s)
	}
	return cell(s)
}

// ErrorsPage returns docs/reference/errors.md: one line per declared id,
// sorted by id, with its slug, exit code, fix hint (a code span: a hint
// holds no backtick), the package that
// declares it and the link to its recovery (04 4.1, Error ids).
func ErrorsPage(rows []cli.Declared) []byte {
	var b strings.Builder
	b.WriteString(`---
type: reference
reader: a user who met an error of romeu or julieta, or a contributor who adds one
---

<!-- Generated by "go generate ./..." from the error table of internal/cli, the errors.go file of each package. Do not edit by hand. -->

# Errors

Every error has a stable id, a slug, an exit code and a fix hint,
declared in the errors.go of the package that raises it
([04 4.1](../spec/04-cli.md#error-ids)). An id is never reused; the
exit codes are in [exit-codes.md](exit-codes.md).

| Id | Slug | Exit | Fix | Declared in | Recovered in |
|---|---|---|---|---|---|
`)
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | `%s` | %d | `%s` | [%s](../../%s) | %s |\n",
			r.ID, r.Slug, r.Exit, cell(r.Fix), strings.TrimSuffix(r.File, "/errors.go"), r.File, recovered(r.RecoveredIn))
	}
	return []byte(b.String())
}

// ExitCodesPage returns docs/reference/exit-codes.md: each exit status
// of both binaries with its meaning and the ids that exit with it, then
// the precedence sentence of 04 4.1, Signals.
func ExitCodesPage(rows []cli.Declared) []byte {
	var b strings.Builder
	b.WriteString(`---
type: reference
reader: a user or a script that reads the exit status of romeu or julieta
---

<!-- Generated by "go generate ./..." from the exit codes and the error table of internal/cli. Do not edit by hand. -->

# Exit codes

Both binaries exit with one of these statuses
([04 4.1](../spec/04-cli.md#41-conventions-both-binaries)); each error
of [errors.md](errors.md) names its own.

| Exit | Meaning | Ids |
|---|---|---|
`)
	for _, e := range cli.ExitCodes {
		var ids []string
		for _, r := range rows {
			if r.Exit == e.Code {
				ids = append(ids, "`"+r.ID+"`")
			}
		}
		fmt.Fprintf(&b, "| %d | %s | %s |\n", e.Code, cell(e.Meaning), strings.Join(ids, ", "))
	}
	fmt.Fprintf(&b, "\n%s\n", cli.SignalPrecedence)
	return []byte(b.String())
}
