// lintFixture is one file of the fixture package: the source, and the
// finding the committed configuration must report for it. A file with
// no linter holds no violation and must stay clean.
type lintFixture struct {
	file    string
	source  string
	linter  string // the linter that reports it
	message string // a part of the message
	// skipped says that linter reports nothing in this file, as revive
	// does in a file with the generated header (ADR 0016); the test
	// holds the skip, so the day it ends the guard of
	// TestGeneratedGoFilesKeepReviveRules can go.
	skipped bool
}

// generatedHeader is the first line of the generated header of 12 12.3,
// the marker golangci-lint skips a file for unless its configuration
// says otherwise (ADR 0016).
const generatedHeader = "// Code generated by tools/ci generate. DO NOT EDIT.\n\n"

// lintFixtures holds one violation of each checker of ADR 0001, rule
// 14, one of each testifylint checker of testifyViolations, one per
// file, each again in the package generated/ with the generated header
// first, so a checker that skips a generated file fails the test, and a
// clean file as the control.
func lintFixtures() []lintFixture {
	fixtures := violationFixtures()
	for _, f := range violationFixtures() {
		f.file = "generated/" + f.file
		f.source = generatedHeader + f.source
		f.skipped = f.linter == "revive"
		fixtures = append(fixtures, f)
	}
	return append(fixtures, lintFixture{
		file: "clean.go",
		source: `// Package fixture holds the lint fixtures.
package fixture

// Documented has a doc comment, an error string in Go style and no
// commented-out code.
func Documented() error {
	return nil
}
`,
	})
}

// violationFixtures holds the violations of every enabled linter, one
// per file, each group in the file named for its linter.
func violationFixtures() []lintFixture {
	var fixtures []lintFixture
	for _, group := range [][]lintFixture{
		rule14Fixtures(),
		testifylintFixtures(),
		errorlintFixtures(),
		usetestingFixtures(),
		thelperFixtures(),
		packageCommentsFixtures(),
	} {
		fixtures = append(fixtures, group...)
	}
	return fixtures
}

// goFileInError matches a file name with a line number in a compiler
// error, as "errorstring.go:5:2".
var goFileInError = regexp.MustCompile(`[\w.-]+\.go:\d+`)

// TestLintConfigReportsEachChecker runs the pinned golangci-lint with
// the committed .golangci.yml over a fixture package that holds one
// violation of each checker of ADR 0001, rule 14 (doc comments, error
// strings, commented-out code) and of each testifylint checker of
// testifyViolations, so a configuration that stops reporting one of
// them fails the build (10 10.1). The fixtures prove those checkers;
// the suite-* checkers of testifylint are covered by
// TestLintConfigLowersNothing.
func TestLintConfigReportsEachChecker(t *testing.T) {
	root := citest.ModuleRoot(t)
	config := filepath.Join(root, ".golangci.yml")
	require.FileExists(t, config)
	fixtures := lintFixtures()

	files := map[string]string{}
	for _, f := range fixtures {
		files[f.file] = f.source
	}
	byFile := lintFixtureModule(t, files, func(dir string) []string {
		// The arguments are the ones of the lint step (Args), with the
		// config by its absolute path, as the run happens in dir.
		args := slices.Clone(Args)
		at := slices.Index(args, ".golangci.yml")
		require.NotEqual(t, -1, at, "lintArgs names .golangci.yml")
		args[at] = config
		return args
	})
	judged := map[string]bool{}
	byLinter := map[string][]lintFixture{}
	for _, f := range fixtures {
		judged[f.file] = true
		if f.linter == "" {
			got := byFile[f.file]
			assert.Empty(t, got, "%s is the control and must stay clean", f.file)
			continue
		}
		byLinter[f.linter] = append(byLinter[f.linter], f)
	}
	// One subtest for each enabled linter, titled by it, judges the
	// fixtures of that linter, the generated copies included.
	for _, linter := range slices.Sorted(maps.Keys(byLinter)) {
		t.Run(linter, func(t *testing.T) {
			for _, f := range byLinter[linter] {
				got := byFile[f.file]
				// A violation file may draw findings from other linters
				// too (staticcheck also reports the error string); one
				// finding of the right linter with the right text is
				// what must exist.
				want := f.linter + ": "
				found := slices.ContainsFunc(got, func(g string) bool {
					return strings.HasPrefix(g, want) && strings.Contains(g, f.message)
				})
				if f.skipped {
					assert.False(t, slices.ContainsFunc(got, func(g string) bool { return strings.HasPrefix(g, want) }),
						"%s: %s now reads a file with the generated header; drop the guard of TestGeneratedGoFilesKeepReviveRules and this skip (ADR 0016), got %q", f.file, f.linter, got)
					continue
				}
				assert.True(t, found, "%s: want a finding %q with %q, got %q", f.file, want, f.message, got)
			}
		})
	}
	// A finding in a file that is none of the fixtures fails by design,
	// and so does one in the control: a default linter that starts to
	// report on a fixture file is a change to review.
	for file := range byFile {
		assert.True(t, judged[file], "a finding in %s, which is no fixture", file)
	}
}

// lintFixtureModule writes files, by slash-separated path, into a module
// of its own with the dependencies of this one, runs the pinned
// golangci-lint in it with the arguments args gives for its directory,
// and returns the findings by file, each as "linter: text".
//
// The fixture needs the module cache this module needs and no network.
// It runs in the environment of the lint step (Env), for the first of
// Targets: the fixture files build for each.
func lintFixtureModule(t *testing.T, files map[string]string, args func(dir string) []string) map[string][]string {
	t.Helper()
	root := citest.ModuleRoot(t)
	dir := t.TempDir()
	for _, name := range []string{"go.mod", "go.sum"} {
		data, err := os.ReadFile(filepath.Join(root, name))
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), data, 0o644))
	}
	for file, source := range files {
		path := filepath.Join(dir, filepath.FromSlash(file))
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, []byte(source), 0o644))
	}

	// The tools are the ones the lint step runs (mise.ResolveLintTools), and
	// the run happens in the fixture's directory, where no mise.toml is.
	tools := citest.PinnedLintTools(t, mise.Path, mise.Environ, mise.ResolveLintTools)

	report := filepath.Join(t.TempDir(), "report.json")
	argv := append(args(dir), "--output.json.path", report, "--output.text.path", os.DevNull)
	out, err := procgroup.CombinedOutput(t.Context(), procgroup.Command{
		Class: procgroup.ToolStep,
		Argv:  append([]string{tools.Linter}, argv...),
		Dir:   dir,
		Env:   Env(Targets[0], tools.GoDir),
	})
	// Exit status 1 means the run found issues, which is the point.
	if err != nil {
		exit, ok := errors.AsType[*procgroup.ExitError](err)
		require.True(t, ok, "golangci-lint run: %v\n%s", err, out)
		require.Equal(t, 1, exit.Code, "exit status of golangci-lint run\n%s", out)
	}

	data, err := os.ReadFile(report)
	require.NoError(t, err, "golangci-lint wrote no report\n%s", out)
	var parsed struct {
		Issues []struct {
			FromLinter string
			Text       string
			Pos        struct{ Filename string }
		}
	}
	require.NoError(t, json.Unmarshal(data, &parsed))

	tail := filepath.ToSlash(filepath.Join(filepath.Base(filepath.Dir(dir)), filepath.Base(dir))) + "/"
	byFile := map[string][]string{} // file -> "linter: text"
	for _, is := range parsed.Issues {
		// A fixture that does not compile is no fixture: the linters
		// report nothing for it.
		// The position of a typecheck finding is the first file of the
		// package; the file that is broken is the one the text names.
		require.NotEqual(t, "typecheck", is.FromLinter, "a fixture does not compile: %s\n%s",
			strings.Join(goFileInError.FindAllString(is.Text, -1), " "), is.Text)
		// The linter names a file relative to a directory of its own
		// choosing, so the fixture's path is what follows the last two
		// elements of dir, which t.TempDir makes unique.
		name := filepath.ToSlash(is.Pos.Filename)
		_, file, found := strings.Cut(name, tail)
		require.True(t, found, "a finding outside the fixture: %s", name)
		byFile[file] = append(byFile[file], is.FromLinter+": "+is.Text)
	}
	return byFile
}
