// PageFixture is the format of the page tests.
type PageFixture struct {
	Schema string            `json:"schema"`
	Name   string            `json:"name" gate:"widening"`
	Items  []PageFixtureItem `json:"items,omitzero" gate:"widening"`
}

// PageFixtureItem is an element of PageFixture's items.
type PageFixtureItem struct {
	Path string `json:"path"`
}

// pageSource is the source the fixture page reads the doc comments from,
// the declarations of the two types above with comments of their own.
const pageSource = `package schema

type PageFixture struct {
	// Schema is "page/v1".
	Schema string
	// Name is the <name>, which a | in a cell
	// does not break.
	Name string
	Items []PageFixtureItem
}

type PageFixtureItem struct {
	// Path is a path.
	Path string
}
`

// pageFixture is the page of PageFixture.
var pageFixture = Page{
	Format: schemagen.Schema{Name: "page.v1", Type: reflect.TypeFor[PageFixture]()},
	Path:   "docs/reference/page.md",
	Title:  "Page",
	Reader: "a reader of the fixture",
	Source: "the fixture types",
	Intro:  "The intro.",
	Tags:   []Tag{{Header: "Gate", Key: "gate"}},
	After:  "The text after.",
	Rules:  []RuleRow{{Field: "name", Rule: "matches `^[a|b]$`", Message: "is bad", Error: "invalid", Scope: "both", Source: "REQ-0175"}},
}

// pageRoot returns a root whose go.mod names the module and whose
// tools/ci/internal/schema holds pageSource.
func pageRoot(t *testing.T) *os.Root {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module github.com/brunovenceslau/romeu-e-julieta\n"), 0o600))
	src := filepath.Join(dir, "tools", "ci", "internal", "schema")
	require.NoError(t, os.MkdirAll(src, 0o700))
	require.NoError(t, os.WriteFile(filepath.Join(src, "page.go"), []byte(pageSource), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(src, "page_test.go"), []byte("package schema\n\ntype PageFixture struct {\n\t// Name is from a test file.\n\tName string\n}\n"), 0o600))
	return citest.RootOf(t, dir)
}

// TestPageOf writes the reference page of a format: the front matter
// and the generated-file header (REQ-1117), the intro with the link to
// the schema, the field table with a column per tag and the meaning from
// each field's doc comment, the text after it, and the rule table.
func TestPageOf(t *testing.T) {
	got, err := PageOf(pageRoot(t), pageFixture)
	require.NoError(t, err)
	want := "---\ntype: reference\nreader: a reader of the fixture\n---\n\n" +
		"<!--\nCode generated by tools/ci generate. DO NOT EDIT.\nSource: the fixture types\n\nGenerated by this command:\n\n\tgo generate ./...\n\n-->\n\n" +
		"# Page\n\nThe intro.\n\nIts JSON Schema is [schemas/page.v1.json](../../schemas/page.v1.json).\n\n" +
		"## Fields\n\n| Field | Type | Required | Gate | Meaning |\n|---|---|---|---|---|\n" +
		"| `schema` | string | yes | - | Schema is \"page/v1\". |\n" +
		"| `name` | string | yes | widening | Name is the \\<name>, which a \\| in a cell does not break. |\n" +
		"| `items` | list of object | no | widening | - |\n" +
		"| `items[].path` | string | yes | widening (via items) | Path is a path. |\n\n" +
		"The text after.\n\n" +
		"## Rules\n\n| Field | Rule | Message | Error | Checked by | Source |\n|---|---|---|---|---|---|\n" +
		"| `name` | matches `^[a\\|b]$` | is bad | invalid | both | REQ-0175 |\n"
	assert.Equal(t, want, string(got))
}

// TestPageOfWithoutRules leaves out the rule table of a format that has
// no rules, and a tree without the format's source has no page.
func TestPageOfWithoutRules(t *testing.T) {
	p := pageFixture
	p.Rules, p.After, p.Tags = nil, "", nil
	got, err := PageOf(pageRoot(t), p)
	require.NoError(t, err)
	assert.NotContains(t, string(got), "## Rules")
	assert.Contains(t, string(got), "| Field | Type | Required | Meaning |\n")

	outs, err := pageOutputs(pageRootWithout(t), []Page{pageFixture})
	require.NoError(t, err)
	assert.Empty(t, outs)
}

// pageRootWithout returns a root with go.mod and no source.
func pageRootWithout(t *testing.T) *os.Root {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module github.com/brunovenceslau/romeu-e-julieta\n"), 0o600))
	return citest.RootOf(t, dir)
}

// TestRegisterPage refuses a second page of one path.
func TestRegisterPage(t *testing.T) {
	saved := pages
	t.Cleanup(func() { pages = saved })
	pages = nil
	RegisterPage(pageFixture)
	assert.Panics(t, func() { RegisterPage(pageFixture) })
}

// TestPageOfFailsItsCheck fails the page whose check fails, so the
// generator does not write a page whose source disagrees with itself.
func TestPageOfFailsItsCheck(t *testing.T) {
	p := pageFixture
	p.Check = func() error { return errors.New("a field on neither") }
	_, err := PageOf(pageRoot(t), p)
	require.ErrorContains(t, err, "docs/reference/page.md: a field on neither")
}

// TestOnlyTheProjectSchemaHasARef pins the formats whose schema holds a
// $ref, a recursive struct type: the run layout's node of project.v1.
// A new one is a choice made on purpose.
func TestOnlyTheProjectSchemaHasARef(t *testing.T) {
	outs, err := Outputs(schemagen.Registered())
	require.NoError(t, err)
	var withRef []string
	for _, o := range outs {
		if strings.Contains(string(o.Content), `"$ref"`) {
			withRef = append(withRef, o.Path)
		}
	}
	assert.Equal(t, []string{"schemas/project.v1.json"}, withRef)
}
