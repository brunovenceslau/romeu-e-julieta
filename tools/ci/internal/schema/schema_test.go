// Fixture is the format of the tests: a schema field, a required name,
// an optional list and an optional time, whose format is asserted.
type Fixture struct {
	Schema string    `json:"schema"`
	Name   string    `json:"name"`
	Tags   []string  `json:"tags,omitempty"`
	At     time.Time `json:"at,omitzero"`
}

// fixture registers Fixture as "fixture.v1".
var fixture = []schemagen.Schema{{Name: "fixture.v1", Type: reflect.TypeFor[Fixture]()}}

// The hint of the fixture tree's release, and a good document in each
// syntax.
const (
	hint      = "# yaml-language-server: $schema=https://raw.githubusercontent.com/example/repo/v1.2.3/schemas/fixture.v1.json\n"
	goodYAML  = hint + "schema: fixture/v1\nname: a\n"
	goodJSON  = `{"schema": "fixture/v1", "name": "a"}`
	otherJSON = `{"schema": "other/v1", "name": 1}`
)

// tree returns the files of a fixture tree that passes: the generated
// schema of the fixture format, VERSION, go.mod, an example in each
// syntax, and testdata files that the check judges and does not judge.
func tree(t *testing.T) map[string]string {
	t.Helper()
	outs, err := Outputs(fixture)
	require.NoError(t, err)
	require.Len(t, outs, 1)
	return map[string]string{
		outs[0].Path:                       string(outs[0].Content),
		"VERSION":                          "1.2.3\n",
		"go.mod":                           "module github.com/example/repo\n\ngo 1.27\n",
		"examples/projects/a.yaml":         goodYAML,
		"examples/state.json":              goodJSON,
		"examples/README.md":               "not judged\n",
		"tools/x/testdata/ok.json":         goodJSON,
		"tools/x/testdata/ok.yml":          "schema: fixture/v1\nname: b\ntags: [x]\n",
		"tools/x/testdata/invalid-a.json":  `{"schema": "fixture/v1"}`,
		"tools/x/testdata/invalid-b.json":  `{"schema": "fixture/v1", "schema": "fixture/v1"}`,
		"tools/x/testdata/broken.yaml":     "a: [\n",
		"tools/x/testdata/no-schema.yaml":  "name: 1\n",
		"tools/x/testdata/keys.yaml":       "{1: 2}\n",
		"tools/x/testdata/fixture.txt":     "schema: fixture/v1\n",
		"internal/x/testdata/deep/ok.yaml": "schema: fixture/v1\nname: c\ntags: []\n",
	}
}

// files returns the tree of m as a commit lists it.
func files(m map[string]string) []check.TreeFile {
	var out []check.TreeFile
	for p, c := range m {
		out = append(out, check.TreeFile{Path: p, Mode: "100644", Content: []byte(c)})
	}
	slices.SortFunc(out, func(a, b check.TreeFile) int { return strings.Compare(a.Path, b.Path) })
	return out
}

// TestGenerateWritesTheFixtureSchema writes the schema of the fixture
// format into a fixture tree, as "go generate ./..." writes the
// registered ones, with the generated-file header as its $comment, and
// the check passes on that tree at HEAD.
func TestGenerateWritesTheFixtureSchema(t *testing.T) {
	outs, err := Outputs(fixture)
	require.NoError(t, err)
	require.Len(t, outs, 1)
	assert.Equal(t, "schemas/fixture.v1.json", outs[0].Path)
	assert.Contains(t, string(outs[0].Content), `"$comment": "Code generated by tools/ci generate. DO NOT EDIT.\nSource: tools/schemagen (the Go type github.com/brunovenceslau/romeu-e-julieta/tools/ci/internal/schema.Fixture)\n\nGenerated by this command:\n\n\tgo generate ./...\n",`)
	assert.Contains(t, string(outs[0].Content), `"const": "fixture/v1"`)

	r := citest.NewTree(t)
	for p, c := range tree(t) {
		r.Write(p, c)
	}
	r.Commit("fixture")
	code, out := citest.Run(t, r, nil, func(ctx context.Context, e check.Env, args []string) (bool, error) {
		return run(ctx, e, args, fixture)
	})
	assert.Equal(t, check.ExitOK, code, out)
	assert.Equal(t, "schema: ok\n", out)

	r.Write("schemas/fixture.v1.json", "{}\n")
	r.Commit("drift")
	code, out = citest.Run(t, r, nil, func(ctx context.Context, e check.Env, args []string) (bool, error) {
		return run(ctx, e, args, fixture)
	})
	assert.Equal(t, check.ExitFail, code, out)
	assert.Equal(t, "schemas/fixture.v1.json: schema drift: differs from the schema tools/schemagen generates; run go generate ./...\nschema: 1 finding(s)\n", out)

	code, out = citest.Run(t, r, nil, Run, "x")
	assert.Equal(t, check.ExitError, code, out)
	assert.Contains(t, out, "schema takes no argument")
}

// TestOf shows the check passing on the fixture tree and failing each
// change of it with the one finding it names.
func TestOf(t *testing.T) {
	got, err := Of(files(tree(t)), fixture)
	require.NoError(t, err)
	assert.Empty(t, got)

	hintMsg := `carries no $schema hint of the release VERSION names: its first comment lines hold "# yaml-language-server: $schema=https://raw.githubusercontent.com/example/repo/v1.2.3/schemas/<name>.json" (03 3.2)`
	for _, c := range []struct {
		name  string
		edit  map[string]string // a path to its new content, or "" to remove it
		where string
		rule  string
		msg   string
	}{
		{"drift", map[string]string{"schemas/fixture.v1.json": "{}\n"}, "schemas/fixture.v1.json", "schema drift", "differs from the schema tools/schemagen generates; run go generate ./..."},
		{"missing", map[string]string{"schemas/fixture.v1.json": ""}, "schemas/fixture.v1.json", "schema missing", "is not committed; run go generate ./..."},
		{"orphan", map[string]string{"schemas/old.v1.json": "{}\n"}, "schemas/old.v1.json", "schema orphan", "no format registered with tools/schemagen generates it"},
		{"example does not validate", map[string]string{"examples/projects/a.yaml": goodYAML + "extra: 1\n"}, "examples/projects/a.yaml", "schema invalid", `does not validate against fixture.v1 at "/ (additionalProperties)"`},
		{"example json does not validate", map[string]string{"examples/state.json": `{"schema": "fixture/v1", "name": 2}`}, "examples/state.json", "schema invalid", `does not validate against fixture.v1 at "/name (type)"`},
		{"testdata does not validate", map[string]string{"tools/x/testdata/ok.json": `{"schema": "fixture/v1", "tags": [1]}`}, "tools/x/testdata/ok.json", "schema invalid", `does not validate against fixture.v1 at "/ (required), /tags/0 (type)"`},
		{"invalid fixture validates", map[string]string{"tools/x/testdata/invalid-a.json": goodJSON}, "tools/x/testdata/invalid-a.json", "schema valid", "validates against fixture.v1, and a fixture named invalid must not"},
		{"no hint", map[string]string{"examples/projects/a.yaml": "schema: fixture/v1\nname: a\n"}, "examples/projects/a.yaml", "schema hint", hintMsg},
		{"hint below the content", map[string]string{"examples/projects/a.yaml": "schema: fixture/v1\n" + hint + "name: a\n"}, "examples/projects/a.yaml", "schema hint", hintMsg},
		{"hint of another release", map[string]string{"examples/projects/a.yaml": strings.Replace(goodYAML, "v1.2.3", "v1.2.2", 1)}, "examples/projects/a.yaml", "schema hint", hintMsg},
		{"hint of no JSON file", map[string]string{"examples/projects/a.yaml": strings.Replace(goodYAML, ".json", ".yaml", 1)}, "examples/projects/a.yaml", "schema hint", hintMsg},
		{"hint of an unknown format", map[string]string{"examples/projects/a.yaml": strings.Replace(goodYAML, "fixture.v1.json", "other.v1.json", 1)}, "examples/projects/a.yaml", "schema unknown", "other.v1 is no format registered with tools/schemagen"},
		{"no VERSION", map[string]string{"VERSION": ""}, "examples/projects/a.yaml", "schema version", "VERSION is not committed, so no release names the hint (REQ-1249)"},
		{"VERSION without a newline", map[string]string{"VERSION": "1.2.3"}, "examples/projects/a.yaml", "schema version", "VERSION holds no <major>.<minor>.<patch> and a newline (REQ-1249)"},
		{"VERSION with a v", map[string]string{"VERSION": "v1.2.3\n"}, "examples/projects/a.yaml", "schema version", "VERSION holds no <major>.<minor>.<patch> and a newline (REQ-1249)"},
		{"module elsewhere", map[string]string{"go.mod": "module example.com/repo\n"}, "examples/projects/a.yaml", "schema version", "go.mod names no github.com module, so no repository names the hint"},
		{"example yaml does not parse", map[string]string{"examples/projects/a.yaml": goodYAML + "name: b\n"}, "examples/projects/a.yaml", "schema parse", "does not decode as one YAML document, or repeats a key"},
		{"example yaml with a key that is not a string", map[string]string{"examples/projects/a.yaml": goodYAML + "1: 2\n"}, "examples/projects/a.yaml", "schema parse", "has a mapping key that is not a string"},
		{"example yaml with a nested key that is not a string", map[string]string{"examples/projects/a.yaml": goodYAML + "tags: [{1: 2}]\n"}, "examples/projects/a.yaml", "schema parse", "has a mapping key that is not a string"},
		{"example yaml of two documents", map[string]string{"examples/projects/a.yaml": goodYAML + "---\nname: b\n"}, "examples/projects/a.yaml", "schema parse", "does not decode as one YAML document, or repeats a key"},
		{"example json does not parse", map[string]string{"examples/state.json": `{"schema": "fixture/v1", "name": "a", "name": "b"}`}, "examples/state.json", "schema parse", "does not decode as one JSON value, or repeats a member name"},
		{"example json names no format", map[string]string{"examples/state.json": `{"name": "a"}`}, "examples/state.json", "schema unknown", "has no schema field of the form <name>/v<n> (REQ-0161)"},
		{"testdata names an unknown format", map[string]string{"tools/x/testdata/other.json": otherJSON}, "tools/x/testdata/other.json", "schema unknown", "other.v1 is no format registered with tools/schemagen"},
		{"testdata names a schema field of another form", map[string]string{"tools/x/testdata/other.json": `{"schema": "other"}`}, "", "", ""},
		{"date-time is asserted", map[string]string{"tools/x/testdata/ok.json": `{"schema": "fixture/v1", "name": "a", "at": "yesterday"}`}, "tools/x/testdata/ok.json", "schema invalid", `does not validate against fixture.v1 at "/at (format)"`},
		{"example json names an unknown format", map[string]string{"examples/state.json": otherJSON}, "examples/state.json", "schema unknown", "other.v1 is no format registered with tools/schemagen"},
	} {
		t.Run(strings.ReplaceAll(c.name, " ", "_"), func(t *testing.T) {
			m := tree(t)
			for p, content := range c.edit {
				if content == "" {
					delete(m, p)
				} else {
					m[p] = content
				}
			}
			got, err := Of(files(m), fixture)
			require.NoError(t, err)
			if c.where == "" {
				assert.Empty(t, got)
				return
			}
			assert.Equal(t, []check.Finding{{Where: c.where, Rule: c.rule, Msg: c.msg}}, got)
		})
	}
}

// TestOfRefusesAFormatItCannotGenerate shows a registered format the
// generator cannot express stopping the check with an error.
func TestOfRefusesAFormatItCannotGenerate(t *testing.T) {
	type bad struct{ C chan int }
	_, err := Of(nil, []schemagen.Schema{{Name: "bad.v1", Type: reflect.TypeFor[bad]()}})
	require.Error(t, err)
	assert.ErrorContains(t, err, "bad.v1: bad.C: the kind chan")
}

// TestOfASubmodule shows that a submodule under schemas/ is a file the
// format does not have.
func TestOfASubmodule(t *testing.T) {
	m := files(tree(t))
	for i := range m {
		if m[i].Path == "schemas/fixture.v1.json" {
			m[i] = check.TreeFile{Path: m[i].Path, Mode: "160000"}
		}
	}
	got, err := Of(m, fixture)
	require.NoError(t, err)
	assert.Equal(t, []check.Finding{
		{Where: "schemas/fixture.v1.json", Rule: "schema missing", Msg: "is not a file"},
	}, got)
}

// TestTheTreePasses runs the check on the tree at HEAD of this
// repository, with the registered formats, through Judge.
func TestTheTreePasses(t *testing.T) {
	root := citest.ModuleRoot(t)
	repo := check.Env{Dir: root}.Repo()
	files, err := check.HeadTree(t.Context(), repo, "HEAD")
	require.NoError(t, err)
	verdicts, err := Judge(t.Context(), check.Commit{Repo: repo, ID: "HEAD", Files: files})
	require.NoError(t, err)
	require.Len(t, verdicts, 1)
	require.NoError(t, verdicts[0].Err)
	assert.Equal(t, "schema", verdicts[0].Name)
	assert.Empty(t, verdicts[0].Findings)
}
