// TestChecksPage checks the inventory of the checks: the front matter
// and the generated-file header (12 12.3), then one line per check, in
// the order given, with "-" for a row that holds no requirement id, the
// place a check runs, and a cell that holds a "|" escaped.
func TestChecksPage(t *testing.T) {
	page := string(ChecksPage([]Check{
		{Name: "format", Guards: "a | b", Usage: "gofmt -l .", Req: "REQ-0820", Fast: true, All: true, Order: 10, Package: "tools/ci/internal/format"},
		{Name: "unit", Guards: "tests", Usage: "go test", Req: "REQ-0824", Fast: true, All: true, Order: 70, RunsCode: true, Job: JobRace, Package: "tools/ci/internal/unit"},
		{Name: "hygiene", Guards: "rules", Usage: "go run ./tools/ci hygiene", Fast: true, All: true, Order: 100, Package: "tools/ci/internal/hygiene"},
		{Name: "pushed range", Guards: "a push", Usage: "fast <remote> <url>", Req: "REQ-0825", Hook: true, Order: 130, Package: "tools/ci/internal/pushedrange"},
		{Name: "race", Guards: "race", Usage: "go test -race", Req: "REQ-0833", All: true, Order: 80, RunsCode: true, Job: JobE2E, Package: "tools/ci/internal/race"},
		{Name: "nowhere", Guards: "none", Usage: "none", Order: 1, Package: "tools/ci/internal/nowhere"},
	}))
	require.True(t, strings.HasPrefix(page, "---\ntype: reference\nreader: "), "front matter first")
	assert.Contains(t, page, "\n---\n\n<!--\nCode generated by tools/ci generate. DO NOT EDIT.\nSource: tools/ci/check_*.go (the registry of tools/ci)\n\nGenerated by this command:\n\n\tgo generate ./...\n\n-->\n\n# Checks\n")
	_, table, found := strings.Cut(page, "|---|---|---|---|---|---|---|---|---|\n")
	require.True(t, found, "the table")
	assert.Equal(t, []string{
		"| `format` | a \\| b | `gofmt -l .` | fast, all | static | 10 | no | REQ-0820 | [tools/ci/internal/format](../../tools/ci/internal/format/) |",
		"| `unit` | tests | `go test` | fast, all | race | 70 | yes | REQ-0824 | [tools/ci/internal/unit](../../tools/ci/internal/unit/) |",
		"| `hygiene` | rules | `go run ./tools/ci hygiene` | fast, all | static | 100 | no | - | [tools/ci/internal/hygiene](../../tools/ci/internal/hygiene/) |",
		"| `pushed range` | a push | `fast <remote> <url>` | fast, in the pre-push hook only | - | 130 | no | REQ-0825 | [tools/ci/internal/pushedrange](../../tools/ci/internal/pushedrange/) |",
		"| `race` | race | `go test -race` | all | e2e | 80 | yes | REQ-0833 | [tools/ci/internal/race](../../tools/ci/internal/race/) |",
		"| `nowhere` | none | `none` | - | - | 1 | no | - | [tools/ci/internal/nowhere](../../tools/ci/internal/nowhere/) |",
	}, strings.Split(strings.TrimSuffix(table, "\n"), "\n"))
}

// TestChecksPageOutput checks that the generator writes the inventory of
// the checks of this binary's registry at ChecksPath.
func TestChecksPageOutput(t *testing.T) {
	outs, err := ChecksPageOutput(nil)
	require.NoError(t, err)
	require.Len(t, outs, 1)
	assert.Equal(t, ChecksPath, outs[0].Path)
	assert.Equal(t, string(ChecksPage(Registered())), string(outs[0].Content))
}
